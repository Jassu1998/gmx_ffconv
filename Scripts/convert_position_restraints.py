#!/usr/bin/env python3
import re
import csv
import argparse

def read_mapping_file(mapping_filename):
    """
    Reads the CSV mapping file generated by ffmap.
    Returns a dictionary {old_index: new_index}.
    """
    mapping = {}
    with open(mapping_filename, 'r') as file:
        reader = csv.reader(file)
        next(reader)  # skip header
        for line in reader:
            old = int(line[0])
            new = int(line[1])
            mapping[old] = new
    return mapping

def rewrite_posres_file(input_file, output_file, mapping):
    """
    Reads input_file (.itp), rewrites position restraint atom indices
    according to mapping, and writes result to output_file.
    """
    lines_out = []
    in_posres = False
    with open(input_file, 'r') as f:
        for line in f:
            stripped = line.rstrip("\n")  # keep track of exact formatting except newline

            # Detect section headers
            if stripped.strip().lower().startswith('['):
                in_posres = 'position_restraints' in stripped.lower()
                lines_out.append(line)
                continue
            # Always keep preprocessor directives, comments, empty lines
            if (not stripped.strip()
                or stripped.strip().startswith(';')
                or stripped.strip().startswith('#')
                or not in_posres):
                lines_out.append(line)
                continue
            # Inside [ position_restraints ] → replace only first integer
            match = re.match(r'(\s*)(\d+)(\s+.*)', line)
            if match:
                prefix, atom_str, suffix = match.groups()
                atom_idx = int(atom_str)
                if atom_idx in mapping:
                    atom_str = str(mapping[atom_idx])
                line = f"{prefix}{atom_str}{suffix}\n"
            lines_out.append(line)
    with open(output_file, 'w') as f:
        f.writelines(lines_out)

def main():
    parser = argparse.ArgumentParser(
        description="Remap atom indices in [ position_restraints ] sections of a GROMACS .itp file."
    )
    parser.add_argument("-itp", required=True, help="Input .itp file")
    parser.add_argument("-mapping", required=True, help="CSV mapping file with old,new columns")
    parser.add_argument("-output", required=True, help="Output .itp file")
    args = parser.parse_args()
    mapping = read_mapping_file(args.mapping)
    rewrite_posres_file(args.itp, args.output, mapping)
    print(f"Rewritten file saved as {args.output}")

if __name__ == "__main__":
    main()